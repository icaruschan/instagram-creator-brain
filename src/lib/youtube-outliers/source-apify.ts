import { ApifyClient } from "apify-client";
import type { CostLedger } from "../instagram-brain/cost";
import { estimateCost } from "../instagram-brain/cost";
import { YOUTUBE_OUTLIER_CONFIG } from "./config";
import { normalizeApifyYouTubeItem } from "./parse";
import type { YouTubeVideo } from "./types";

export const YOUTUBE_ACTOR = "streamers/youtube-scraper";

function tokens(): string[] {
  return [
    process.env.APIFY_TOKEN,
    process.env.BACKUP_APIFY_TOKEN,
    process.env.BACKUP_APIFY_TOKEN_2,
    process.env.BACKUP_APIFY_TOKEN_3,
    process.env.BACKUP_APIFY_TOKEN_4,
  ].filter((token): token is string => Boolean(token));
}

async function withApify<T>(operation: (client: ApifyClient) => Promise<T>): Promise<T> {
  const available = tokens();
  if (!available.length) throw new Error("APIFY_TOKEN is required for YouTube outlier scans");
  let lastError: unknown;
  for (const token of available) {
    try {
      return await operation(new ApifyClient({ token }));
    } catch (error) {
      lastError = error;
      console.warn("Apify token attempt failed; trying the next configured token.");
    }
  }
  throw lastError instanceof Error ? lastError : new Error("All Apify token attempts failed");
}

export function channelStartUrl(channelUrl: string): string {
  const clean = channelUrl.trim().replace(/\/+$/, "").replace(/\/(videos|shorts|streams|featured)$/i, "");
  if (/^https?:\/\//i.test(clean)) return clean;
  if (clean.startsWith("@")) return `https://www.youtube.com/${clean}`;
  if (/^UC[\w-]{22}$/.test(clean)) return `https://www.youtube.com/channel/${clean}`;
  return `https://www.youtube.com/@${clean}`;
}

/** Actor input for a channel listing: newest long-form + newest Shorts, no streams, no subtitles. */
export function channelListingInput(channelUrl: string, longForm: number, shorts: number) {
  return {
    startUrls: [{ url: channelStartUrl(channelUrl) }],
    maxResults: longForm,
    maxResultsShorts: shorts,
    maxResultStreams: 0,
    sortVideosBy: "NEWEST",
    transcriptionAndSubtitle: "NONE",
  };
}

/** Actor input for subtitles of chosen videos only. Existing subtitles only: never the paid speech-to-text. */
export function subtitlesInput(videoUrls: string[]) {
  return {
    startUrls: videoUrls.map((url) => ({ url })),
    maxResults: videoUrls.length,
    maxResultsShorts: 0,
    maxResultStreams: 0,
    transcriptionAndSubtitle: "ALWAYS_SUBTITLES",
    subtitlesLanguage: "en",
    subtitlesFormat: "srt",
    preferAutoGeneratedSubtitles: false,
  };
}

async function runActor(input: Record<string, unknown>, expectedItems: number, label: string, ledger?: CostLedger): Promise<any[]> {
  const estimate = estimateCost("apify-youtube-video", expectedItems);
  ledger?.ensure(estimate, label);
  let reported: number | null = null;
  let count = 0;
  try {
    return await withApify(async (client) => {
      const run: any = await client.actor(YOUTUBE_ACTOR).call(input);
      reported = Number.isFinite(Number(run?.usageTotalUsd)) ? Number(run.usageTotalUsd) : null;
      const { items } = await client.dataset(run.defaultDatasetId).listItems();
      count = items.length;
      return items as any[];
    });
  } finally {
    // Pay-per-event: actual = items written × price; usageTotalUsd when Apify reports it.
    ledger?.record("apify-youtube-video", `${label} (${count} items)`, estimate, reported ?? (count ? estimateCost("apify-youtube-video", count) : null));
  }
}

export async function scrapeChannelWithApify(
  channelUrl: string,
  options: { longForm?: number; shorts?: number; ledger?: CostLedger; now?: Date } = {},
): Promise<YouTubeVideo[]> {
  const longForm = options.longForm ?? YOUTUBE_OUTLIER_CONFIG.longFormPerChannel;
  const shorts = options.shorts ?? YOUTUBE_OUTLIER_CONFIG.shortsPerChannel;
  const items = await runActor(channelListingInput(channelUrl, longForm, shorts), longForm + shorts, `youtube channel ${channelUrl}`, options.ledger);
  return items.filter((item) => item?.id && !item?.error).map((item) => normalizeApifyYouTubeItem(item, options.now));
}

/** Subtitles for a few chosen videos (Map videoId → plain transcript). */
export async function fetchTranscriptsWithApify(videoUrls: string[], ledger?: CostLedger): Promise<Map<string, string>> {
  const out = new Map<string, string>();
  if (!videoUrls.length) return out;
  const items = await runActor(subtitlesInput(videoUrls), videoUrls.length, `youtube subtitles x${videoUrls.length}`, ledger);
  for (const item of items) {
    const video = normalizeApifyYouTubeItem(item);
    if (video.id && video.transcript) out.set(video.id, video.transcript);
  }
  return out;
}
